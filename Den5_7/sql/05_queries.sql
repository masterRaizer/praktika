/* ===================================================================
   База данных «Киноточка» — день 5: 13 SQL-запросов.
   Запускать после 01_create.sql, 02_data.sql (день 4) и 04_den5.sql.
   Значения, которые вводит пользователь, передаются параметрами (@…);
   запросы 11 и 12 выполнены через sp_executesql — так же, как их выполняет приложение
   (SqlCommand с SqlParameter), без склеивания пользовательского ввода с текстом SQL.
   =================================================================== */
USE Киноточка;
GO
SET NOCOUNT ON;

/* 1. SELECT + фильтрация + сортировка: активные фильмы длиннее 100 минут, сначала самые длинные */
SELECT Название AS Фильм, ДлительностьМин AS Минут, ВозрастнойРейтинг AS Возраст
FROM dbo.Фильмы
WHERE Активен = 1 AND ДлительностьМин > 100
ORDER BY ДлительностьМин DESC;

/* 2. JOIN двух таблиц: фильмы с жанрами, по алфавиту */
SELECT f.Название AS Фильм, g.Название AS Жанр, f.ВозрастнойРейтинг AS Возраст
FROM dbo.Фильмы f
JOIN dbo.Жанры g ON g.КодЖанра = f.КодЖанра
ORDER BY g.Название, f.Название;

/* 3. GROUP BY + COUNT: сколько фильмов в каждом жанре (LEFT JOIN — жанры без фильмов тоже видны) */
SELECT g.Название AS Жанр, COUNT(f.КодФильма) AS Фильмов
FROM dbo.Жанры g
LEFT JOIN dbo.Фильмы f ON f.КодЖанра = g.КодЖанра
GROUP BY g.Название
ORDER BY Фильмов DESC, Жанр;

/* 4. Представление Афиша: сеансы 21.11.2026 со свободными местами */
SELECT FORMAT(НачалоСеанса, 'HH:mm') AS Начало, Фильм, Зал, Формат, БазоваяЦена AS Цена, Свободно
FROM dbo.Афиша
WHERE CAST(НачалоСеанса AS DATE) = '2026-11-21'
ORDER BY НачалоСеанса;

/* 5. Представление ВыручкаПоФильмам: фильмы с выручкой больше нуля */
SELECT Фильм, Оплачено, Возвращено, Выручка
FROM dbo.ВыручкаПоФильмам
WHERE Оплачено > 0
ORDER BY Выручка DESC;

/* 6. Агрегатные функции: число заказов и сумма по статусам (через представление СуммыЗаказов) */
SELECT st.Название AS Статус, COUNT(*) AS Заказов, SUM(s.Итого) AS Сумма, CAST(AVG(s.Итого) AS DECIMAL(10,2)) AS СреднийЧек
FROM dbo.Заказы o
JOIN dbo.СтатусыЗаказа st ON st.КодСтатуса = o.КодСтатуса
JOIN dbo.СуммыЗаказов s   ON s.КодЗаказа = o.КодЗаказа
GROUP BY st.КодСтатуса, st.Название
ORDER BY st.КодСтатуса;

/* 7. Топ зрителей по сумме оплаченных и завершённых заказов: JOIN + GROUP BY + TOP */
SELECT TOP (3) u.ФИО AS Зритель, COUNT(*) AS Заказов, SUM(s.Итого) AS Сумма
FROM dbo.Заказы o
JOIN dbo.Пользователи u ON u.КодПользователя = o.КодПользователя
JOIN dbo.СуммыЗаказов s ON s.КодЗаказа = o.КодЗаказа
WHERE o.КодСтатуса IN (3, 4)
GROUP BY u.ФИО
ORDER BY Сумма DESC;

/* 8. Средняя оценка фильмов: AVG + HAVING (не меньше двух отзывов) */
SELECT f.Название AS Фильм, COUNT(*) AS Отзывов, CAST(AVG(CAST(r.Оценка AS DECIMAL(3,2))) AS DECIMAL(3,2)) AS Оценка
FROM dbo.Отзывы r
JOIN dbo.Фильмы f ON f.КодФильма = r.КодФильма
GROUP BY f.Название
HAVING COUNT(*) >= 2
ORDER BY Оценка DESC;

/* 9. Подзапрос NOT EXISTS: будущие сеансы, на которые ещё нет ни одного заказа */
SELECT FORMAT(s.НачалоСеанса, 'dd.MM HH:mm') AS Сеанс, f.Название AS Фильм, h.Название AS Зал
FROM dbo.Сеансы s
JOIN dbo.Фильмы f ON f.КодФильма = s.КодФильма
JOIN dbo.Залы h   ON h.КодЗала = s.КодЗала
WHERE s.НачалоСеанса > '2026-11-20'
  AND NOT EXISTS (SELECT 1 FROM dbo.Заказы o WHERE o.КодСеанса = s.КодСеанса)
ORDER BY s.НачалоСеанса;

/* 10. Журнал действий: последние записи с именем пользователя */
SELECT TOP (10) FORMAT(j.ВремяДействия, 'dd.MM.yyyy HH:mm') AS Время, ISNULL(u.ФИО, N'—') AS Пользователь,
       j.Действие, ISNULL(j.Подробности, N'') AS Подробности
FROM dbo.ЖурналДействий j
LEFT JOIN dbo.Пользователи u ON u.КодПользователя = j.КодПользователя
ORDER BY j.ВремяДействия DESC;

/* 11. Параметризованный запрос: поиск фильмов по части названия и жанру */
EXEC sys.sp_executesql
    N'SELECT f.Название AS Фильм, g.Название AS Жанр
      FROM dbo.Фильмы f JOIN dbo.Жанры g ON g.КодЖанра = f.КодЖанра
      WHERE f.Название LIKE N''%'' + @Поиск + N''%''
        AND (@КодЖанра IS NULL OR f.КодЖанра = @КодЖанра)
      ORDER BY f.Название',
    N'@Поиск NVARCHAR(100), @КодЖанра INT',
    @Поиск = N'о', @КодЖанра = NULL;

/* 12. Параметризованный запрос: выручка за период */
EXEC sys.sp_executesql
    N'SELECT CAST(p.ДатаСоздания AS DATE) AS День,
             SUM(CASE WHEN p.ВидОперации = N''ОПЛАТА'' THEN p.Сумма ELSE -p.Сумма END) AS Выручка,
             COUNT(*) AS Операций
      FROM dbo.Платежи p
      WHERE p.Успешно = 1 AND p.ДатаСоздания >= @С AND p.ДатаСоздания < DATEADD(DAY, 1, @По)
      GROUP BY CAST(p.ДатаСоздания AS DATE)
      ORDER BY День',
    N'@С DATE, @По DATE',
    @С = '2026-11-10', @По = '2026-11-19';
GO

/* 13. Связь 1:1: зрители и их профили (у пользователя не больше одного профиля) */
SELECT u.ФИО AS Зритель, u.ЭлПочта, ISNULL(p.Город, N'—') AS Город,
       ISNULL(FORMAT(p.ДатаРождения, 'dd.MM.yyyy'), N'—') AS ДатаРождения,
       CASE p.ПодпискаНаРассылку WHEN 1 THEN N'да' ELSE N'нет' END AS Рассылка
FROM dbo.Пользователи u
JOIN dbo.ПрофилиЗрителей p ON p.КодПользователя = u.КодПользователя
ORDER BY u.ФИО;
