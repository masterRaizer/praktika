def esc(s):
    return s.replace("'", "''")


def main():
    out = [HEAD]
    for table, (tdesc, cols) in TABLES.items():
        out.append(f"-- {table}")
        out.append(
            f"IF EXISTS (SELECT 1 FROM sys.extended_properties WHERE major_id = OBJECT_ID(N'dbo.{table}') "
            f"AND minor_id = 0 AND name = N'MS_Description')\n"
            f"    EXEC sys.sp_dropextendedproperty N'MS_Description', N'SCHEMA', N'dbo', N'TABLE', N'{table}';\n"
            f"EXEC sys.sp_addextendedproperty N'MS_Description', N'{esc(tdesc)}', N'SCHEMA', N'dbo', N'TABLE', N'{table}';")
        for col, cdesc in cols.items():
            out.append(
                f"IF EXISTS (SELECT 1 FROM sys.extended_properties ep JOIN sys.columns c ON c.object_id = ep.major_id "
                f"AND c.column_id = ep.minor_id WHERE ep.major_id = OBJECT_ID(N'dbo.{table}') AND c.name = N'{col}' "
                f"AND ep.name = N'MS_Description')\n"
                f"    EXEC sys.sp_dropextendedproperty N'MS_Description', N'SCHEMA', N'dbo', N'TABLE', N'{table}', N'COLUMN', N'{col}';\n"
                f"EXEC sys.sp_addextendedproperty N'MS_Description', N'{esc(cdesc)}', N'SCHEMA', N'dbo', N'TABLE', N'{table}', N'COLUMN', N'{col}';")
        out.append("GO")
    out.append("""
PRINT N'Дополнения дня 5 установлены: таблицы ЖурналДействий и ПрофилиЗрителей, представления Афиша и ВыручкаПоФильмам, описания всех таблиц и полей.';
GO
""")
    with open(OUT, "w", encoding="utf-8-sig") as f:
        f.write("\n".join(out))
    print("ok:", OUT, "таблиц:", len(TABLES), "полей:", sum(len(c) for _, c in TABLES.values()))


if __name__ == "__main__":
    main()
