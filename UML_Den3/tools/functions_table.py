HEAD = ["№", "Функция", "Кто выполняет", "Входные данные", "Что изменяет", "Результат пользователю",
        "Проверка прав", "Проверка данных", "Комментарий"]


def main():
    with open(os.path.join(OUT, "functions.csv"), "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f, delimiter=";")
        w.writerow(HEAD)
        for r in F:
            w.writerow([*r[:6], "да" if r[6] else "", "да" if r[7] else "", r[8]])
    rows = ["| " + " | ".join(["№", "Функция", "Кто", "Входные данные", "Что изменяет", "Результат",
                               "П", "К", "Комментарий"]) + " |",
            "|" + "---|" * 9]
    for r in F:
        rows.append("| " + " | ".join([r[0], r[1], r[2], r[3], r[4], r[5], "✔" if r[6] else "", "✔" if r[7] else "",
                                       r[8]]) + " |")
    # таблица вставляется в README между метками <!-- TABLE --> и <!-- /TABLE -->
    readme = os.path.join(OUT, "README.md")
    text = open(readme, encoding="utf-8").read()
    a = text.index("<!-- TABLE -->")
    b = text.find("<!-- /TABLE -->")
    b = b + len("<!-- /TABLE -->") if b >= 0 else a + len("<!-- TABLE -->")
    text = text[:a] + "<!-- TABLE -->\n" + "\n".join(rows) + "\n<!-- /TABLE -->" + text[b:]
    with open(readme, "w", encoding="utf-8") as f:
        f.write(text)
    p = sum(1 for r in F if r[6])
    k = sum(1 for r in F if r[7])
    both = sum(1 for r in F if r[6] and r[7])
    none = sum(1 for r in F if not r[6] and not r[7])
    print(f"функций: {len(F)}, права: {p}, данные: {k}, обе: {both}, без проверок: {none}")


if __name__ == "__main__":
    main()
