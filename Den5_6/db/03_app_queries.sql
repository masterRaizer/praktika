/* ===================================================================
   База данных «Киноточка» — запросы приложения (дни 5–6).
   Те же запросы, что выполняет программа (классы папки Data).
   В программе значения передаются параметрами SqlParameter — здесь
   параметры объявлены через DECLARE, чтобы файл можно было выполнить в SSMS.
   Запускать после 01_create.sql и 02_data.sql. Данные не изменяются:
   все изменяющие запросы выполняются в транзакции с откатом.
   =================================================================== */
USE Киноточка;
GO
SET NOCOUNT ON;

/* 1. Авторизация: поиск учётной записи по электронной почте (пароль проверяется в программе по хешу) */
DECLARE @ЭлПочта NVARCHAR(100) = N'admin@kinotochka.ru';
SELECT p.КодПользователя, p.ФИО, p.ЭлПочта, r.Обозначение AS Роль, p.Заблокирован, LEFT(p.ХешПароля, 22) + N'…' AS ХешПароля
FROM dbo.Пользователи p JOIN dbo.Роли r ON r.КодРоли = p.КодРоли
WHERE p.ЭлПочта = @ЭлПочта;

/* 2. Поиск фильмов по части названия и жанру (NULL — без фильтра) */
DECLARE @Поиск NVARCHAR(150) = N'звёзд', @КодЖанра INT = NULL, @ТолькоВПрокате BIT = 0;
SELECT f.КодФильма, f.Название, g.Название AS Жанр, f.ДлительностьМин, f.ВозрастнойРейтинг,
       (SELECT COUNT(*) FROM dbo.Сеансы s WHERE s.КодФильма = f.КодФильма) AS Сеансов
FROM dbo.Фильмы f JOIN dbo.Жанры g ON g.КодЖанра = f.КодЖанра
WHERE (@Поиск IS NULL OR f.Название LIKE N'%' + @Поиск + N'%')
  AND (@КодЖанра IS NULL OR f.КодЖанра = @КодЖанра)
  AND (@ТолькоВПрокате = 0 OR f.Активен = 1)
ORDER BY f.Название;

/* 3. Предстоящие сеансы с числом проданных мест (действующие заказы) */
DECLARE @Сейчас DATETIME2(0) = '2026-11-21T08:00:00';
SELECT s.КодСеанса, FORMAT(s.НачалоСеанса, 'dd.MM.yyyy HH:mm') AS Начало, f.Название AS Фильм, z.Название AS Зал, s.Формат, s.БазоваяЦена,
       (SELECT COUNT(*) FROM dbo.Заказы o JOIN dbo.Билеты t ON t.КодЗаказа = o.КодЗаказа
          JOIN dbo.СтатусыЗаказа st ON st.КодСтатуса = o.КодСтатуса
        WHERE o.КодСеанса = s.КодСеанса AND st.Обозначение IN (N'ЗАБРОНИРОВАН', N'ОПЛАЧИВАЕТСЯ', N'ОПЛАЧЕН', N'ЗАВЕРШЁН')) AS Продано,
       z.КоличествоРядов * z.МестВРяду AS Мест
FROM dbo.Сеансы s JOIN dbo.Фильмы f ON f.КодФильма = s.КодФильма JOIN dbo.Залы z ON z.КодЗала = s.КодЗала
WHERE s.НачалоСеанса >= @Сейчас
ORDER BY s.НачалоСеанса;

/* 4. Заказы с суммой из представления СуммыЗаказов; для зрителя — только его заказы */
DECLARE @КодПользователя INT = 4;
SELECT o.КодЗаказа, ISNULL(u.ФИО, N'(продажа в кассе)') AS Покупатель, f.Название AS Фильм, st.Название AS Статус,
       ISNULL(v.КоличествоБилетов, 0) AS Билетов, ISNULL(v.Итого, 0) AS Итого
FROM dbo.Заказы o
JOIN dbo.Сеансы s ON s.КодСеанса = o.КодСеанса JOIN dbo.Фильмы f ON f.КодФильма = s.КодФильма
JOIN dbo.СтатусыЗаказа st ON st.КодСтатуса = o.КодСтатуса
LEFT JOIN dbo.Пользователи u ON u.КодПользователя = o.КодПользователя
LEFT JOIN dbo.СуммыЗаказов v ON v.КодЗаказа = o.КодЗаказа
WHERE (@КодПользователя IS NULL OR o.КодПользователя = @КодПользователя)
ORDER BY o.ДатаСоздания DESC;

/* 5. Проверка связей перед удалением фильма (внешние ключи без каскадного удаления) */
DECLARE @Код INT = 1;
SELECT (SELECT COUNT(*) FROM dbo.Сеансы WHERE КодФильма = @Код) AS Сеансов,
       (SELECT COUNT(*) FROM dbo.Отзывы WHERE КодФильма = @Код) AS Отзывов;

/* 6. Проверка, свободен ли зал: пересечение с другим сеансом (длительность фильма + 15 минут на уборку) */
DECLARE @КодФильма INT = 1, @КодЗала INT = 1, @Начало DATETIME2(0) = '2026-11-21T19:30:00', @КодСеанса INT = 0;
SELECT TOP 1 f2.Название + N' в ' + FORMAT(s2.НачалоСеанса, 'dd.MM.yyyy HH:mm') AS ЗанятСеансом
FROM dbo.Сеансы s2 JOIN dbo.Фильмы f2 ON f2.КодФильма = s2.КодФильма
CROSS JOIN (SELECT ДлительностьМин FROM dbo.Фильмы WHERE КодФильма = @КодФильма) f
WHERE s2.КодЗала = @КодЗала AND s2.КодСеанса <> @КодСеанса
  AND s2.НачалоСеанса < DATEADD(MINUTE, f.ДлительностьМин + 15, @Начало)
  AND @Начало < DATEADD(MINUTE, f2.ДлительностьМин + 15, s2.НачалоСеанса);

/* 7. Добавление, изменение и удаление записи (как в программе) — в транзакции с откатом */
BEGIN TRANSACTION;
    DECLARE @НовыйКод INT;
    INSERT INTO dbo.Фильмы (Название, КодЖанра, ДлительностьМин, ВозрастнойРейтинг, Описание, Активен)
    VALUES (N'Новогодний экспресс', 2, 104, N'12+', N'Пример добавления', 1);
    SET @НовыйКод = CAST(SCOPE_IDENTITY() AS INT);
    UPDATE dbo.Фильмы SET ДлительностьМин = 110 WHERE КодФильма = @НовыйКод;
    SELECT КодФильма, Название, ДлительностьМин FROM dbo.Фильмы WHERE КодФильма = @НовыйКод;
    DELETE FROM dbo.Фильмы WHERE КодФильма = @НовыйКод;
ROLLBACK TRANSACTION;

/* 8. Попытка удалить фильм, у которого есть сеансы: база отклоняет (ошибка 547, внешний ключ) */
BEGIN TRY
    BEGIN TRANSACTION;
    DELETE FROM dbo.Фильмы WHERE КодФильма = 1;
    ROLLBACK TRANSACTION;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    SELECT ERROR_NUMBER() AS НомерОшибки, N'Удаление фильма с сеансами отклонено' AS Результат;
END CATCH;

/* 9. Показатели главной страницы */
SELECT (SELECT COUNT(*) FROM dbo.Фильмы WHERE Активен = 1) AS ФильмовВПрокате,
       (SELECT COUNT(*) FROM dbo.Заказы o JOIN dbo.СтатусыЗаказа st ON st.КодСтатуса = o.КодСтатуса
         WHERE st.Обозначение IN (N'ЗАБРОНИРОВАН', N'ОПЛАЧИВАЕТСЯ', N'ОПЛАЧЕН')) AS ДействующихЗаказов,
       (SELECT ISNULL(SUM(CASE WHEN ВидОперации = N'ОПЛАТА' THEN Сумма ELSE -Сумма END), 0) FROM dbo.Платежи WHERE Успешно = 1) AS Выручка;
GO
