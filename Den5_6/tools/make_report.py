def table(headers, rows, widths=None, cls=""):
    cols = "".join(f'<col style="width:{w}">' for w in widths) if widths else ""
    head = "".join(f"<th>{E(h)}</th>" for h in headers)
    body = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f'<table class="{cls}"><colgroup>{cols}</colgroup><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>'


def fig(path, caption, width="100%"):
    return f'<figure><img src="{path}" style="width:{width}"><figcaption>{E(caption)}</figcaption></figure>'


def code(text):
    return f"<pre>{E(text.strip())}</pre>"


def tests():
    md = open(os.path.join(ROOT, "tests", "Результаты_тестирования.md"), encoding="utf-8").read()
    info = [l for l in md.splitlines() if l.startswith("Дата:") or l.startswith("Проверок:")]
    rows = []
    for line in md.splitlines():
        if re.match(r"^\| \d+ \|", line):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            cells = [E(c) for c in cells]
            cells[-1] = f'<b class="{"ok" if cells[-1] == "Пройден" else "bad"}">{cells[-1]}</b>'
            rows.append(cells)
    return info, rows


def sql_block(number):
    text = open(os.path.join(ROOT, "db", "03_app_queries.sql"), encoding="utf-8-sig").read()
    parts = re.split(r"\n(?=/\* \d+\. )", text)
    for p in parts:
        if p.startswith(f"/* {number}. "):
            return code(p.split("\n/* ")[0])
    return ""


